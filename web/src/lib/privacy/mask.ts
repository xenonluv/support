// 개인정보 가림: LLM 호출 전과 DB 저장 전에 반드시 거친다 (CLAUDE.md 개인정보 규칙).
// 규칙 기반이라 모든 경우를 잡지는 못한다 — 구술할 때 성명 대신 식별번호로 말하도록 안내한다.

const SURNAMES =
  "김이박최정강조윤장임한오서신권황안송류유전홍고문양손배백허남심노하곽성차주우구민진나지엄채원천방공현함변염여추도소석선설마길연위표명기반왕금옥육인맹제모탁국어은편용예경봉사부";
const COMPOUND_SURNAMES = ["남궁", "황보", "제갈", "선우", "독고", "사공", "서문"];
const HONORIFIC = "(?=\\s?(?:어르신|할머니|할아버지|선생님|여사님|여사|씨|님))";

// 성씨 글자로 시작하지만 이름이 아닌 흔한 낱말
const NOT_NAMES = new Set([
  "오늘", "이번", "이분", "이제", "이미", "정말", "조금", "한번", "한참", "전에", "전부", "지금", "지난",
  "주변", "주인", "이웃", "오전", "오후", "어제", "요즘", "아까", "모든", "모두", "우리", "안쪽", "위층",
  "장시간", "고객", "고령", "독거", "방금", "변함", "성실", "기존", "예전", "경우", "동네", "도움",
]);

const NAME = new RegExp(
  `(?<![가-힣])((?:${COMPOUND_SURNAMES.join("|")})[가-힣]{1,2}|[${SURNAMES}][가-힣]{1,2})${HONORIFIC}`,
  "g",
);

const RULES: [RegExp, string][] = [
  [/[\w.+-]+@[\w-]+(?:\.[\w-]+)+/g, "[이메일]"],
  [/(?<!\d)\d{6}-?[1-4]\d{6}(?!\d)/g, "[주민번호]"],
  [/(?<!\d)(?:01[016789]|0[2-6]\d?)-?\d{3,4}-?\d{4}(?!\d)/g, "[전화번호]"],
  // 도로명: ○○로 123, ○○로123번길 45 (뒤에 분·시간·회 같은 단위가 오면 주소가 아님)
  [/[가-힣0-9]+(?:로|길)\s?\d{1,4}(?:번길\s?\d{1,4})?(?:-\d{1,4})?(?![0-9])(?!\s?(?:분|시간|개|회|일|초|번(?!길)|km|m))/g, "[주소]"],
  // 지번: ○○동 123-4번지
  [/[가-힣]+동\s?\d{1,5}(?:-\d{1,5})?번지/g, "[주소]"],
  // 동·호수: 101동 1203호
  [/\d{1,4}동\s?\d{1,5}호/g, "[주소]"],
];

/** 텍스트에서 개인정보를 [이름]·[전화번호]·[주소] 등으로 바꾼다. 여러 번 거쳐도 결과가 같다. */
export function maskPersonalInfo(text: string): { text: string; count: number } {
  let count = 0;
  let out = text;
  for (const [pattern, label] of RULES) {
    out = out.replace(pattern, () => {
      count++;
      return label;
    });
  }
  out = out.replace(NAME, (match) => {
    if (NOT_NAMES.has(match)) return match;
    count++;
    return "[이름]";
  });
  return { text: out, count };
}
