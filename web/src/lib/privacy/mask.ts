// 개인정보 가림: LLM 호출 전과 DB 저장 전에 반드시 거친다 (CLAUDE.md 개인정보 규칙).
// 규칙 기반이라 모든 경우를 잡지는 못한다 — 구술할 때 성명 대신 식별번호로 말하도록 안내한다.

const SURNAMES =
  "김이박최정강조윤장임한오서신권황안송류유전홍고문양손배백허남심노하곽성차주우구민진나지엄채원천방공현함변염여추도소석선설마길연위표명기반왕금옥육인맹제모탁국어은편용예경봉사부";
const COMPOUND_SURNAMES = ["남궁", "황보", "제갈", "선우", "독고", "사공", "서문"];
const HONORIFIC = "(?=\\s?(?:어르신|할머니|할아버지|선생님|여사님|여사|씨|님))";

// 성씨 글자로 시작하지만 이름이 아닌 흔한 낱말
const NOT_NAMES = new Set([
  "오늘", "이번", "이분", "이제", "이미", "정말", "조금", "한번", "한참", "전에", "전부", "지금", "지난",
  "주변", "주인", "이웃", "오전", "오후", "어제", "요즘", "아까", "모든", "모두", "우리", "안쪽", "위층",
  "장시간", "고객", "고령", "독거", "방금", "변함", "성실", "기존", "예전", "경우", "동네", "도움", "주말",
  "평소", "이후", "한낮", "오랜만",
  // 돌봄 구술에 흔한 꾸밈말·낱말 ("혼자 사시는 어르신", "부부 어르신", "방문 오신 선생님")
  "사는", "사시는", "모시는", "지내는", "오신", "오시는", "편찮은", "연로한",
  "남자", "여자", "부부", "노부부", "방문", "기관", "구청", "주민",
]);

// 성씨 글자로 시작하는 직함·친족어 (뒤에 '님'이 붙어도 이름이 아님)
const TITLES = new Set([
  "선생", "사장", "사모", "어머", "고모", "이모", "장모", "원장", "소장", "과장", "팀장", "부장", "실장", "계장",
  "반장", "회장", "기사", "주무관", "지원사", "변호사", "공무원",
  "이장", "구청장", "주치의", "도우미", "한의사", "봉사자", "신부",
]);

// 이름 뒤에 붙을 수 있는 조사 — 떼고 보았을 때 일반 낱말이면 이름이 아니다 ("오늘은" → "오늘")
const PARTICLE = /(?:은|는|이|가|을|를|에|의|도|만|과|와|께|랑)$/;

const NAME = new RegExp(
  `(?<![가-힣])((?:${COMPOUND_SURNAMES.join("|")})[가-힣]{1,2}|[${SURNAMES}][가-힣]{1,2})${HONORIFIC}`,
  "g",
);

const RULES: [RegExp, string][] = [
  [/[\w.+-]+@[\w-]+(?:\.[\w-]+)+/g, "[이메일]"],
  [/(?<!\d)\d{6}-?[1-4]\d{6}(?!\d)/g, "[주민번호]"],
  // 하이픈·점·띄어쓰기 구분 모두 (음성 인식은 "010 1234 5678"처럼 적기도 한다)
  [/(?<!\d)(?:01[016789]|0[2-6]\d?)[-.\s]?\d{3,4}[-.\s]?\d{4}(?!\d)/g, "[전화번호]"],
  // 도로명 ①: ○○로123번길 45 (번길이 있으면 주소가 확실)
  [/[가-힣0-9]+(?:로|길)\s?\d{1,4}번길\s?\d{1,4}(?:-\d{1,4})?/g, "[주소]"],
  // 도로명 ②: "○○구 화정로 123"처럼 시·구·군 바로 다음에 올 때만
  // ("위로 150", "병원으로 3명", "엘리베이터로 3층"은 주소가 아니다)
  [/(?<=[가-힣](?:시|구|군)\s)[가-힣0-9]+(?:대로|로|길)\s?\d{1,4}(?:-\d{1,4})?(?![0-9])(?!\s?(?:분|시간|개|회|일|초|명|층|번(?!길)))/g, "[주소]"],
  // 지번: ○○동 123-4번지
  [/[가-힣]+동\s?\d{1,5}(?:-\d{1,5})?번지/g, "[주소]"],
  // 동·호수: 101동 1203호
  [/\d{1,4}동\s?\d{1,5}호/g, "[주소]"],
];

/** 텍스트에서 개인정보를 [이름]·[전화번호]·[주소] 등으로 바꾼다. 여러 번 거쳐도 결과가 같다. */
export function maskPersonalInfo(text: string): { text: string; count: number } {
  let count = 0;
  let out = text;
  for (const [pattern, label] of RULES) {
    out = out.replace(pattern, () => {
      count++;
      return label;
    });
  }
  out = out.replace(NAME, (match) => {
    if (NOT_NAMES.has(match) || NOT_NAMES.has(match.replace(PARTICLE, "")) || TITLES.has(match)) return match;
    count++;
    return "[이름]";
  });
  return { text: out, count };
}
